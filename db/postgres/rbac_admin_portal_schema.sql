-- RBAC Admin Portal schema for PostgreSQL
-- Naming convention requested:
--   * Master tables      : TblMstRBAC...
--   * Transaction tables : TblTrnRBAC...
--   * Primary key names  : ...Uno
--   * All primary keys are identity columns.
-- Bilingual support:
--   * English columns use suffix En (VARCHAR)
--   * Arabic columns use suffix Ar (VARCHAR, UTF-8)
-- Audit fields:
--   * EnteredOn, EnteredBy, ModifiedOn, ModifiedBy, DeletedOn, DeletedBy
-- Active flag:
--   * IsActive SMALLINT in all tables (1=active, 0=inactive)

-- ============================================================
-- 1) MASTER TABLES (TblMstRBAC*)
-- ============================================================

