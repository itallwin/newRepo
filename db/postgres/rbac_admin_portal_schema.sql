    LastNameAr          VARCHAR(80),
    EmailAddr           VARCHAR(255) NOT NULL,
    StaffTypeCode       VARCHAR(20) DEFAULT 'PERMANENT' NOT NULL,
    AccountExpiryOn     TIMESTAMP NOT NULL,
    PasswordHash        VARCHAR(500) NOT NULL,
    PasswordChangedOn   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DesignationEn       VARCHAR(120),
    DesignationAr       VARCHAR(120),
    CompanyUno          BIGINT,
    DepartmentUno       BIGINT NOT NULL,
    DivisionUno         BIGINT NOT NULL,
    SectionUno          BIGINT,
    FailedPasswordAttemptCount SMALLINT DEFAULT 0 NOT NULL,
    IsAccountLocked     SMALLINT DEFAULT 0 NOT NULL,
    AccountLockedOn     TIMESTAMP,
    FirstLoginOn        TIMESTAMP,
    LastLoginOn         TIMESTAMP,
    LastFailedLoginOn   TIMESTAMP,
    ExternalSubjectId   VARCHAR(200),
    IsActive            SMALLINT DEFAULT 1 NOT NULL,
    InactiveOn          TIMESTAMP,
    InactivatedOn       TIMESTAMP,
    InactivatedBy       VARCHAR(128),
    ActivatedOn         TIMESTAMP,
    ActivatedBy         VARCHAR(128),
    InactivationReasonEn VARCHAR(1000),
    InactivationReasonAr VARCHAR(1000),
    EnteredOn           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EnteredBy           VARCHAR(128),
    ModifiedOn          TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ModifiedBy          VARCHAR(128),
    DeletedOn           TIMESTAMP,
    DeletedBy           VARCHAR(128),
    CONSTRAINT UQ_MstUser_Emp UNIQUE (EmployeeId),
    CONSTRAINT UQ_MstUser_Email UNIQUE (EmailAddr),
    CONSTRAINT FK_MstUser_Company FOREIGN KEY (CompanyUno) REFERENCES TblMstRBACCompany(CompanyUno),
    CONSTRAINT FK_MstUser_Department FOREIGN KEY (DepartmentUno) REFERENCES TblMstRBACDepartment(DepartmentUno),
    CONSTRAINT FK_MstUser_Division FOREIGN KEY (DivisionUno) REFERENCES TblMstRBACDivision(DivisionUno),
    CONSTRAINT FK_MstUser_Section FOREIGN KEY (SectionUno) REFERENCES TblMstRBACSection(SectionUno),
    CONSTRAINT FK_MstUser_DivDept FOREIGN KEY (DivisionUno, DepartmentUno)
        REFERENCES TblMstRBACDivision(DivisionUno, DepartmentUno),
    CONSTRAINT FK_MstUser_SecDiv FOREIGN KEY (SectionUno, DivisionUno)
        REFERENCES TblMstRBACSection(SectionUno, DivisionUno),
    CONSTRAINT CK_MstUser_IsActive CHECK (IsActive IN (0, 1)),
    CONSTRAINT CK_MstUser_FailedPwd CHECK (FailedPasswordAttemptCount BETWEEN 0 AND 99),
    CONSTRAINT CK_MstUser_IsLocked CHECK (IsAccountLocked IN (0, 1)),
    CONSTRAINT CK_MstUser_LockRule CHECK (
        (FailedPasswordAttemptCount < 3) OR
        (FailedPasswordAttemptCount >= 3 AND IsAccountLocked = 1)
    ),
    CONSTRAINT CK_MstUser_LockTs CHECK (
        (IsAccountLocked = 0) OR
        (IsAccountLocked = 1 AND AccountLockedOn IS NOT NULL)
    ),
    CONSTRAINT CK_MstUser_StaffType CHECK (StaffTypeCode IN ('PERMANENT', 'EXTERNAL')),
    CONSTRAINT CK_MstUser_ExpiryLimit CHECK (
        (StaffTypeCode = 'PERMANENT' AND
            AccountExpiryOn >= EnteredOn AND
            AccountExpiryOn <= (EnteredOn + INTERVAL '12 months')
        ) OR
        (StaffTypeCode = 'EXTERNAL' AND
            AccountExpiryOn >= EnteredOn AND
            AccountExpiryOn <= (EnteredOn + INTERVAL '6 months')
        )
    )
);

CREATE INDEX IX_MstUser_Company ON TblMstRBACUser(CompanyUno);
