CREATE OR REPLACE FUNCTION fn_mstuser_valemaildomain()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    vdomain VARCHAR(255);
    vcount  BIGINT;
BEGIN
    IF NEW.EmailAddr IS NULL THEN
        RETURN NEW;
    END IF;

    IF POSITION('@' IN NEW.EmailAddr) <= 1 THEN
        RAISE EXCEPTION 'Invalid EmailAddr format.';
    END IF;

    vdomain := LOWER(TRIM(SPLIT_PART(NEW.EmailAddr, '@', 2)));

    IF vdomain IS NULL OR vdomain = '' OR POSITION('.' IN vdomain) = 0 THEN
        RAISE EXCEPTION 'Invalid EmailAddr format.';
    END IF;

    SELECT COUNT(1)
      INTO vcount
      FROM TblMstRBACAllowedEmailDomain d
     WHERE LOWER(d.EmailDomain) = vdomain
       AND d.IsActive = 1
       AND d.DeletedOn IS NULL;

    IF vcount = 0 THEN
        RAISE EXCEPTION 'Email domain not allowed in user master: %', vdomain;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER TRG_MstUser_ValEmailDomain
BEFORE INSERT OR UPDATE OF EmailAddr ON TblMstRBACUser
FOR EACH ROW
EXECUTE FUNCTION fn_mstuser_valemaildomain();


CREATE OR REPLACE FUNCTION fn_mstuser_setexpiry()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    vbasets TIMESTAMP;
BEGIN
    vbasets := COALESCE(NEW.EnteredOn, CURRENT_TIMESTAMP);

    IF NEW.StaffTypeCode IS NULL THEN
        NEW.StaffTypeCode := 'PERMANENT';
    END IF;

    IF NEW.AccountExpiryOn IS NULL THEN
        IF NEW.StaffTypeCode = 'EXTERNAL' THEN
            NEW.AccountExpiryOn := vbasets + INTERVAL '6 months';
        ELSE
            NEW.AccountExpiryOn := vbasets + INTERVAL '12 months';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER TRG_MstUser_SetExpiry
BEFORE INSERT OR UPDATE OF StaffTypeCode, EnteredOn, AccountExpiryOn ON TblMstRBACUser
FOR EACH ROW
EXECUTE FUNCTION fn_mstuser_setexpiry();


CREATE OR REPLACE FUNCTION fn_trnuseract_unauth()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    vunauthaccessuno BIGINT;
    vunauthcount     BIGINT;
    vopenbreachcnt   BIGINT;
    vaccesspointcode VARCHAR(20);
    vreasoncode      VARCHAR(40);
BEGIN
    IF COALESCE(NEW.IsAuthorized, 1) = 0 OR NEW.ActivityTypeCode = 'UNAUTHORIZED' THEN
        IF NEW.ActivityTypeCode = 'LOGIN' THEN
            vaccesspointcode := 'LOGIN';
            vreasoncode := 'LOGIN_DENIED';
        ELSIF NEW.ActivityTypeCode = 'API_CALL' THEN
            vaccesspointcode := 'API';
            vreasoncode := 'API_FORBIDDEN';
        ELSIF NEW.ActionUno IS NOT NULL THEN
            vaccesspointcode := 'ACTION';
            vreasoncode := 'ACTION_DENIED';
        ELSE
            vaccesspointcode := 'PAGE';
            vreasoncode := 'PAGE_DENIED';
        END IF;

        INSERT INTO TblTrnRBACUnauthAccess (
            UserUno, ActivityUno, AttemptOn, AccessPointCode, ModuleUno, PageUno, ActionUno,
            RoutePath, DenialReasonCode, ClientIpAddress, UserAgent, DetailJson,
            IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
        ) VALUES (
            NEW.UserUno, NEW.ActivityUno, NEW.ActivityOn, vaccesspointcode, NEW.ModuleUno, NEW.PageUno, NEW.ActionUno,
            NEW.RoutePath, vreasoncode, NEW.ClientIpAddress, NEW.UserAgent, NEW.DetailJson,
            1, CURRENT_TIMESTAMP, NEW.EnteredBy, CURRENT_TIMESTAMP, NEW.ModifiedBy
        ) RETURNING UnauthAccessUno INTO vunauthaccessuno;

        IF NEW.UserUno IS NOT NULL THEN
            SELECT COUNT(1)
              INTO vunauthcount
              FROM TblTrnRBACUnauthAccess ua
             WHERE ua.UserUno = NEW.UserUno
               AND ua.AttemptOn >= CURRENT_TIMESTAMP - INTERVAL '10 minutes'
               AND ua.DeletedOn IS NULL;

            IF vunauthcount >= 5 THEN
                SELECT COUNT(1)
                  INTO vopenbreachcnt
                  FROM TblTrnRBACSecurityIncident si
                 WHERE si.UserUno = NEW.UserUno
                   AND si.IncidentTypeCode = 'BRUTE_FORCE'
                   AND si.IncidentStatusCode IN ('OPEN', 'IN_PROGRESS')
                   AND si.IncidentOn >= CURRENT_TIMESTAMP - INTERVAL '10 minutes'
                   AND si.DeletedOn IS NULL;

                IF vopenbreachcnt = 0 THEN
                    INSERT INTO TblTrnRBACSecurityIncident (
                        UserUno, UnauthAccessUno, IncidentTypeCode, SeverityCode, IncidentOn,
                        IncidentStatusCode, DetectedByCode, DetailJson,
                        IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
                    ) VALUES (
                        NEW.UserUno, vunauthaccessuno, 'BRUTE_FORCE', 'HIGH', CURRENT_TIMESTAMP,
                        'OPEN', 'SYSTEM', '{"rule":"5 unauthorized attempts in 10 minutes"}',
                        1, CURRENT_TIMESTAMP, NEW.EnteredBy, CURRENT_TIMESTAMP, NEW.ModifiedBy
                    );
                END IF;
            END IF;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER TRG_TrnUserAct_Unauth
AFTER INSERT ON TblTrnRBACUserActivity
FOR EACH ROW
EXECUTE FUNCTION fn_trnuseract_unauth();


CREATE OR REPLACE FUNCTION fn_mstuser_expiryhist()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    vhistuno BIGINT;
BEGIN
    IF NEW.InactivatedOn IS NOT NULL
       AND (OLD.InactivatedOn IS NULL OR OLD.InactivatedOn <> NEW.InactivatedOn) THEN
        INSERT INTO TblTrnRBACUserExpiryHist (
            UserUno, ExpiredOn, ExpirySourceCode, EventCommentEn,
            IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
        ) VALUES (
            NEW.UserUno, NEW.InactivatedOn, 'ACCOUNT_EXPIRED', NEW.InactivationReasonEn,
            1, CURRENT_TIMESTAMP, NEW.InactivatedBy, CURRENT_TIMESTAMP, NEW.ModifiedBy
        );
    END IF;

    IF NEW.ActivatedOn IS NOT NULL
       AND (OLD.ActivatedOn IS NULL OR OLD.ActivatedOn <> NEW.ActivatedOn) THEN
        SELECT MAX(UserExpiryHistUno)
          INTO vhistuno
          FROM TblTrnRBACUserExpiryHist
         WHERE UserUno = NEW.UserUno
           AND ReactivatedOn IS NULL
           AND DeletedOn IS NULL;

        IF vhistuno IS NOT NULL THEN
            UPDATE TblTrnRBACUserExpiryHist
               SET ReactivatedOn = NEW.ActivatedOn,
                   ReactivatedBy = NEW.ActivatedBy,
                   ModifiedOn = CURRENT_TIMESTAMP,
                   ModifiedBy = COALESCE(NEW.ModifiedBy, NEW.ActivatedBy)
             WHERE UserExpiryHistUno = vhistuno;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER TRG_MstUser_ExpiryHist
AFTER UPDATE OF InactivatedOn, ActivatedOn, InactivatedBy, ActivatedBy ON TblMstRBACUser
FOR EACH ROW
EXECUTE FUNCTION fn_mstuser_expiryhist();


CREATE OR REPLACE FUNCTION fn_trnrbacpermaudit()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    vchangedby VARCHAR(128);
BEGIN
    IF TG_OP = 'INSERT' THEN
        vchangedby := COALESCE(NEW.ModifiedBy, NEW.EnteredBy);
        INSERT INTO TblTrnRBACPermissionAudit (
            PermissionUno, AuditActionCode, ChangedOn, ChangedBy,
            NewGranteeTypeCode, NewRoleUno, NewUserGroupUno, NewActionUno, NewGrantAcess, NewIsActive, NewDeletedOn,
            IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
        ) VALUES (
            NEW.PermissionUno, 'INSERT', CURRENT_TIMESTAMP, vchangedby,
            NEW.GranteeTypeCode, NEW.RoleUno, NEW.UserGroupUno, NEW.ActionUno, NEW.GrantAcess, NEW.IsActive, NEW.DeletedOn,
            1, CURRENT_TIMESTAMP, vchangedby, CURRENT_TIMESTAMP, vchangedby
        );
        RETURN NULL;
    ELSIF TG_OP = 'UPDATE' THEN
        vchangedby := COALESCE(NEW.ModifiedBy, OLD.ModifiedBy);
        INSERT INTO TblTrnRBACPermissionAudit (
            PermissionUno, AuditActionCode, ChangedOn, ChangedBy,
            OldGranteeTypeCode, OldRoleUno, OldUserGroupUno, OldActionUno, OldGrantAcess, OldIsActive, OldDeletedOn,
            NewGranteeTypeCode, NewRoleUno, NewUserGroupUno, NewActionUno, NewGrantAcess, NewIsActive, NewDeletedOn,
            IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
        ) VALUES (
            OLD.PermissionUno, 'UPDATE', CURRENT_TIMESTAMP, vchangedby,
            OLD.GranteeTypeCode, OLD.RoleUno, OLD.UserGroupUno, OLD.ActionUno, OLD.GrantAcess, OLD.IsActive, OLD.DeletedOn,
            NEW.GranteeTypeCode, NEW.RoleUno, NEW.UserGroupUno, NEW.ActionUno, NEW.GrantAcess, NEW.IsActive, NEW.DeletedOn,
            1, CURRENT_TIMESTAMP, vchangedby, CURRENT_TIMESTAMP, vchangedby
        );
        RETURN NULL;
    ELSE
        vchangedby := COALESCE(OLD.ModifiedBy, OLD.EnteredBy);
        INSERT INTO TblTrnRBACPermissionAudit (
            PermissionUno, AuditActionCode, ChangedOn, ChangedBy,
            OldGranteeTypeCode, OldRoleUno, OldUserGroupUno, OldActionUno, OldGrantAcess, OldIsActive, OldDeletedOn,
            IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
        ) VALUES (
            OLD.PermissionUno, 'DELETE', CURRENT_TIMESTAMP, vchangedby,
            OLD.GranteeTypeCode, OLD.RoleUno, OLD.UserGroupUno, OLD.ActionUno, OLD.GrantAcess, OLD.IsActive, OLD.DeletedOn,
            1, CURRENT_TIMESTAMP, vchangedby, CURRENT_TIMESTAMP, vchangedby
        );
        RETURN NULL;
    END IF;
END;
$$;

CREATE TRIGGER TRG_TrnRBACPermAudit
AFTER INSERT OR UPDATE OR DELETE ON TblTrnRBACPermission
FOR EACH ROW
EXECUTE FUNCTION fn_trnrbacpermaudit();
