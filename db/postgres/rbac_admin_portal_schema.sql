-- Effective user actions from:
--   a) Direct user-role permission
--   b) Group-role permission
--   c) Direct group permission
CREATE OR REPLACE VIEW VRBACEffectiveUserAction AS
SELECT DISTINCT
    U.UserUno,
    P.ActionUno,
    'USER_ROLE' AS SourceType
FROM TblMstRBACUser U
JOIN TblTrnRBACUserRole UR
  ON UR.UserUno = U.UserUno
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCode = 'ROLE'
 AND P.RoleUno = UR.RoleUno
WHERE U.IsActive = 1
  AND U.DeletedOn IS NULL
  AND UR.IsActive = 1
  AND UR.DeletedOn IS NULL
  AND P.IsActive = 1
  AND P.DeletedOn IS NULL
  AND P.GrantAcess = 'Y'
  AND (UR.ValidTo IS NULL OR UR.ValidTo >= CURRENT_DATE)

UNION ALL

SELECT DISTINCT
    GM.UserUno,
    P.ActionUno,
    'GROUP_ROLE' AS SourceType
FROM TblTrnRBACGroupMembership GM
JOIN TblTrnRBACGroupRole GR
  ON GR.UserGroupUno = GM.UserGroupUno
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCode = 'ROLE'
 AND P.RoleUno = GR.RoleUno
WHERE GM.IsActive = 1
  AND GM.DeletedOn IS NULL
  AND GR.IsActive = 1
  AND GR.DeletedOn IS NULL
  AND P.IsActive = 1
  AND P.DeletedOn IS NULL
  AND P.GrantAcess = 'Y'
  AND (GM.ValidTo IS NULL OR GM.ValidTo >= CURRENT_DATE)

UNION ALL

SELECT DISTINCT
    GM.UserUno,
    P.ActionUno,
    'GROUP_PERMISSION' AS SourceType
FROM TblTrnRBACGroupMembership GM
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCode = 'GROUP'
 AND P.UserGroupUno = GM.UserGroupUno
WHERE GM.IsActive = 1
  AND GM.DeletedOn IS NULL
  AND P.IsActive = 1
  AND P.DeletedOn IS NULL
  AND P.GrantAcess = 'Y'
  AND (GM.ValidTo IS NULL OR GM.ValidTo >= CURRENT_DATE);

