CREATE INDEX IX_MstUser_Division ON TblMstRBACUser(DivisionUno);
CREATE INDEX IX_MstUser_Section ON TblMstRBACUser(SectionUno);
CREATE INDEX IX_MstUser_ExpiryOn ON TblMstRBACUser(AccountExpiryOn);


