CREATE TABLE TblMstRBACUser (
    UserUno             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EmployeeId          VARCHAR(40) NOT NULL,
    FirstNameEn         VARCHAR(80) NOT NULL,
    FirstNameAr         VARCHAR(80),
