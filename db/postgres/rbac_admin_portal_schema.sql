CREATE OR REPLACE VIEW VRBACUserUsageDailyStat AS
SELECT
    DATE_TRUNC('day', A.ActivityOn)::date AS UsageOn,
    A.UserUno,
    A.PageUno,
    A.ActionUno,
    COUNT(1) AS TotalEventCount,
    SUM(CASE WHEN A.ActivityTypeCode = 'PAGE_VIEW' THEN 1 ELSE 0 END) AS PageViewCount,
    SUM(CASE WHEN A.ActivityTypeCode = 'ACTION_EXECUTE' THEN 1 ELSE 0 END) AS ActionExecCount,
    SUM(CASE WHEN COALESCE(A.IsAuthorized, 1) = 0 THEN 1 ELSE 0 END) AS UnauthorizedCount
FROM TblTrnRBACUserActivity A
WHERE A.IsActive = 1
  AND A.DeletedOn IS NULL
GROUP BY DATE_TRUNC('day', A.ActivityOn)::date, A.UserUno, A.PageUno, A.ActionUno;

