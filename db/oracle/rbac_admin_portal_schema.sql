CREATE OR REPLACE TRIGGER TRG_TrnUserAct_Unauth
AFTER INSERT ON TblTrnRBACUserActivity
FOR EACH ROW
DECLARE
    VUnauthAccessUno NUMBER;
    VUnauthCount     NUMBER;
    VOpenBreachCnt   NUMBER;
    VAccessPointCode VARCHAR2(20);
    VReasonCode      VARCHAR2(40);
BEGIN
    IF NVL(:NEW.IsAuthorized, 1) = 0 OR :NEW.ActivityTypeCode = 'UNAUTHORIZED' THEN
        IF :NEW.ActivityTypeCode = 'LOGIN' THEN
            VAccessPointCode := 'LOGIN';
            VReasonCode := 'LOGIN_DENIED';
        ELSIF :NEW.ActivityTypeCode = 'API_CALL' THEN
            VAccessPointCode := 'API';
            VReasonCode := 'API_FORBIDDEN';
        ELSIF :NEW.ActionUno IS NOT NULL THEN
            VAccessPointCode := 'ACTION';
            VReasonCode := 'ACTION_DENIED';
        ELSE
            VAccessPointCode := 'PAGE';
            VReasonCode := 'PAGE_DENIED';
        END IF;

        INSERT INTO TblTrnRBACUnauthAccess (
            UserUno, ActivityUno, AttemptOn, AccessPointCode, ModuleUno, PageUno, ActionUno,
            RoutePath, DenialReasonCode, ClientIpAddress, UserAgent, DetailJson,
            IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
        ) VALUES (
            :NEW.UserUno, :NEW.ActivityUno, :NEW.ActivityOn, VAccessPointCode, :NEW.ModuleUno, :NEW.PageUno, :NEW.ActionUno,
            :NEW.RoutePath, VReasonCode, :NEW.ClientIpAddress, :NEW.UserAgent, :NEW.DetailJson,
            1, SYSTIMESTAMP, :NEW.EnteredBy, SYSTIMESTAMP, :NEW.ModifiedBy
        )
        RETURNING UnauthAccessUno INTO VUnauthAccessUno;

        IF :NEW.UserUno IS NOT NULL THEN
            SELECT COUNT(1)
              INTO VUnauthCount
              FROM TblTrnRBACUnauthAccess UA
             WHERE UA.UserUno = :NEW.UserUno
               AND UA.AttemptOn >= SYSTIMESTAMP - NUMTODSINTERVAL(10, 'MINUTE')
               AND UA.DeletedOn IS NULL;

            IF VUnauthCount >= 5 THEN
                SELECT COUNT(1)
                  INTO VOpenBreachCnt
                  FROM TblTrnRBACSecurityIncident SI
                 WHERE SI.UserUno = :NEW.UserUno
                   AND SI.IncidentTypeCode = 'BRUTE_FORCE'
                   AND SI.IncidentStatusCode IN ('OPEN', 'IN_PROGRESS')
                   AND SI.IncidentOn >= SYSTIMESTAMP - NUMTODSINTERVAL(10, 'MINUTE')
                   AND SI.DeletedOn IS NULL;

                IF VOpenBreachCnt = 0 THEN
                    INSERT INTO TblTrnRBACSecurityIncident (
                        UserUno, UnauthAccessUno, IncidentTypeCode, SeverityCode, IncidentOn,
                        IncidentStatusCode, DetectedByCode, DetailJson,
                        IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
                    ) VALUES (
                        :NEW.UserUno, VUnauthAccessUno, 'BRUTE_FORCE', 'HIGH', SYSTIMESTAMP,
                        'OPEN', 'SYSTEM', '{"rule":"5 unauthorized attempts in 10 minutes"}',
                        1, SYSTIMESTAMP, :NEW.EnteredBy, SYSTIMESTAMP, :NEW.ModifiedBy
                    );
                END IF;
            END IF;
        END IF;
    END IF;
END;
