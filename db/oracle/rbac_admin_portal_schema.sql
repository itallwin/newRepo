    updated_at           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(128),
    CONSTRAINT fk_rbac_group_company
        FOREIGN KEY (company_id) REFERENCES rbac_company(company_id),
    CONSTRAINT fk_rbac_group_role_tmpl
