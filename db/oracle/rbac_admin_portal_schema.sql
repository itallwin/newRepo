-- RBAC Admin Portal schema for Oracle Database
-- Naming convention requested:
--   * Master tables      : TblMstRBAC...
--   * Transaction tables : TblTrnRBAC...
--   * Primary key names  : ...Uno (RoleUno, UserUno, PermissionUno, etc.)
--   * All primary keys are identity columns.

-- ============================================================
-- 1) MASTER TABLES (TblMstRBAC*)
-- ============================================================

CREATE TABLE TblMstRBACCompany (
    CompanyUno          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CompanyCode         VARCHAR2(30) NOT NULL,
    CompanyName         VARCHAR2(120) NOT NULL,
    StatusCd            VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CreatedAt           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CreatedBy           VARCHAR2(128),
    UpdatedAt           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UpdatedBy           VARCHAR2(128),
    CONSTRAINT UQ_MstRBACCompany_Code UNIQUE (CompanyCode),
    CONSTRAINT CK_MstRBACCompany_Status CHECK (StatusCd IN ('ACTIVE', 'INACTIVE', 'DRAFT'))
);

CREATE TABLE TblMstRBACDepartment (
    DepartmentUno       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CompanyUno          NUMBER NOT NULL,
    DepartmentCode      VARCHAR2(30) NOT NULL,
    DepartmentName      VARCHAR2(120) NOT NULL,
    StatusCd            VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CreatedAt           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CreatedBy           VARCHAR2(128),
    UpdatedAt           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UpdatedBy           VARCHAR2(128),
    CONSTRAINT FK_MstRBACDept_Company FOREIGN KEY (CompanyUno) REFERENCES TblMstRBACCompany(CompanyUno),
    CONSTRAINT UQ_MstRBACDept_CompCode UNIQUE (CompanyUno, DepartmentCode),
    CONSTRAINT CK_MstRBACDept_Status CHECK (StatusCd IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX IX_MstRBACDept_Company ON TblMstRBACDepartment(CompanyUno);

