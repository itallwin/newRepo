-- RBAC Admin Portal schema for Oracle Database
-- Based on screens in rbac-admin-portal.html:
-- Modules, Pages, Actions, Roles, Geo Scope, User Groups, Users

-- ============================================================
-- 1) MASTER TABLES
-- ============================================================

CREATE TABLE rbac_company (
    company_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_code        VARCHAR2(30) NOT NULL,
    company_name        VARCHAR2(120) NOT NULL,
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    created_by          VARCHAR2(128),
    updated_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          VARCHAR2(128),
    CONSTRAINT uq_rbac_company_code UNIQUE (company_code),
    CONSTRAINT ck_rbac_company_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE', 'DRAFT'))
);

CREATE TABLE rbac_department (
    department_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id          NUMBER NOT NULL,
    department_code     VARCHAR2(30) NOT NULL,
    department_name     VARCHAR2(120) NOT NULL,
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    created_by          VARCHAR2(128),
    updated_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          VARCHAR2(128),
    CONSTRAINT fk_rbac_dept_company
        FOREIGN KEY (company_id) REFERENCES rbac_company(company_id),
    CONSTRAINT uq_rbac_dept_comp_code UNIQUE (company_id, department_code),
    CONSTRAINT ck_rbac_dept_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_rbac_dept_company ON rbac_department(company_id);

CREATE TABLE rbac_country (
    country_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    iso2_code           CHAR(2) NOT NULL,
    country_name        VARCHAR2(120) NOT NULL,
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT uq_rbac_country_iso2 UNIQUE (iso2_code),
    CONSTRAINT uq_rbac_country_name UNIQUE (country_name),
    CONSTRAINT ck_rbac_country_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE rbac_embassy (
    embassy_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_id          NUMBER NOT NULL,
    embassy_code        VARCHAR2(40) NOT NULL,
    embassy_name        VARCHAR2(200) NOT NULL,
    embassy_type_cd     VARCHAR2(30) DEFAULT 'EMBASSY' NOT NULL,
    city_name           VARCHAR2(120),
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT fk_rbac_emb_country
        FOREIGN KEY (country_id) REFERENCES rbac_country(country_id),
    CONSTRAINT uq_rbac_emb_code UNIQUE (embassy_code),
    CONSTRAINT uq_rbac_emb_country_name UNIQUE (country_id, embassy_name),
    CONSTRAINT ck_rbac_emb_type
        CHECK (embassy_type_cd IN ('EMBASSY', 'CONSULATE', 'HIGH_COMMISSION', 'OTHER')),
    CONSTRAINT ck_rbac_emb_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_rbac_emb_country ON rbac_embassy(country_id);

-- ============================================================
-- 2) MODULE / PAGE / ACTION (PERMISSION CATALOG)
-- ============================================================

CREATE TABLE rbac_module (
    module_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_code         VARCHAR2(30) NOT NULL,
    module_name         VARCHAR2(120) NOT NULL,
    icon_name           VARCHAR2(20),
    description_txt     VARCHAR2(1000),
    sort_order          NUMBER(6) DEFAULT 0 NOT NULL,
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    created_by          VARCHAR2(128),
    updated_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          VARCHAR2(128),
    CONSTRAINT uq_rbac_module_code UNIQUE (module_code),
    CONSTRAINT uq_rbac_module_name UNIQUE (module_name),
    CONSTRAINT ck_rbac_module_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE rbac_page (
    page_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id           NUMBER NOT NULL,
    page_code           VARCHAR2(40) NOT NULL,
    page_name           VARCHAR2(150) NOT NULL,
    route_path          VARCHAR2(300),
    description_txt     VARCHAR2(1000),
    sort_order          NUMBER(6) DEFAULT 0 NOT NULL,
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    created_by          VARCHAR2(128),
    updated_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          VARCHAR2(128),
    CONSTRAINT fk_rbac_page_module
        FOREIGN KEY (module_id) REFERENCES rbac_module(module_id),
    CONSTRAINT uq_rbac_page_code UNIQUE (page_code),
    CONSTRAINT uq_rbac_page_mod_name UNIQUE (module_id, page_name),
    CONSTRAINT ck_rbac_page_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_rbac_page_module ON rbac_page(module_id);

CREATE TABLE rbac_action (
    action_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id             NUMBER NOT NULL,
    action_code         VARCHAR2(60) NOT NULL,
    action_name         VARCHAR2(150) NOT NULL,
    action_type_cd      VARCHAR2(20) NOT NULL,
    description_txt     VARCHAR2(1000),
    sort_order          NUMBER(6) DEFAULT 0 NOT NULL,
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    created_by          VARCHAR2(128),
    updated_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          VARCHAR2(128),
    CONSTRAINT fk_rbac_action_page
        FOREIGN KEY (page_id) REFERENCES rbac_page(page_id),
    CONSTRAINT uq_rbac_action_code UNIQUE (action_code),
    CONSTRAINT uq_rbac_action_page_type UNIQUE (page_id, action_type_cd),
    CONSTRAINT ck_rbac_action_type
        CHECK (action_type_cd IN ('VIEW', 'ADD', 'EDIT', 'DELETE', 'APPROVE', 'EXPORT', 'PRINT', 'CUSTOM')),
    CONSTRAINT ck_rbac_action_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE'))
);

CREATE INDEX ix_rbac_action_page ON rbac_action(page_id);

-- ============================================================
-- 3) ROLES AND ROLE-PERMISSIONS
-- ============================================================

CREATE TABLE rbac_role (
    role_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code           VARCHAR2(40) NOT NULL,
    role_name           VARCHAR2(150) NOT NULL,
    description_txt     VARCHAR2(1000),
    access_model_cd     VARCHAR2(20) DEFAULT 'USER_LINKED' NOT NULL,
    scope_level_cd      VARCHAR2(20) DEFAULT 'GLOBAL' NOT NULL,
    is_system_role      CHAR(1) DEFAULT 'N' NOT NULL,
    is_super_admin_role CHAR(1) DEFAULT 'N' NOT NULL,
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    created_by          VARCHAR2(128),
    updated_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          VARCHAR2(128),
    CONSTRAINT uq_rbac_role_code UNIQUE (role_code),
    CONSTRAINT uq_rbac_role_name UNIQUE (role_name),
    CONSTRAINT ck_rbac_role_access_model
        CHECK (access_model_cd IN ('USER_LINKED', 'GEO_SCOPED', 'GROUP_LINKED')),
    CONSTRAINT ck_rbac_role_scope_level
        CHECK (scope_level_cd IN ('GLOBAL', 'COUNTRY', 'EMBASSY')),
    CONSTRAINT ck_rbac_role_sys
        CHECK (is_system_role IN ('Y', 'N')),
    CONSTRAINT ck_rbac_role_super
        CHECK (is_super_admin_role IN ('Y', 'N')),
    CONSTRAINT ck_rbac_role_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE', 'DRAFT'))
);

CREATE INDEX ix_rbac_role_access_model ON rbac_role(access_model_cd);

CREATE TABLE rbac_role_permission (
    role_id             NUMBER NOT NULL,
    action_id           NUMBER NOT NULL,
    grant_flag          CHAR(1) DEFAULT 'Y' NOT NULL,
    granted_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    granted_by          VARCHAR2(128),
    CONSTRAINT pk_rbac_role_perm PRIMARY KEY (role_id, action_id),
    CONSTRAINT fk_rbac_role_perm_role
        FOREIGN KEY (role_id) REFERENCES rbac_role(role_id),
    CONSTRAINT fk_rbac_role_perm_action
        FOREIGN KEY (action_id) REFERENCES rbac_action(action_id),
    CONSTRAINT ck_rbac_role_perm_grant
        CHECK (grant_flag IN ('Y', 'N'))
);

CREATE INDEX ix_rbac_role_perm_action ON rbac_role_permission(action_id);

-- Geo-scoped restrictions for GEO_SCOPED roles
CREATE TABLE rbac_role_country_scope (
    role_id             NUMBER NOT NULL,
