-- ============================================================
-- 7) HELPER VIEW: EFFECTIVE USER ACTIONS
-- ============================================================
-- Combines:
--   a) direct user-role permissions
--   b) group-role permissions
--   c) direct group permissions
CREATE OR REPLACE VIEW v_rbac_effective_user_action AS
SELECT DISTINCT
    u.user_id,
    rp.action_id,
    'USER_ROLE' AS source_type
FROM rbac_user_account u
JOIN rbac_user_role ur
  ON ur.user_id = u.user_id
JOIN rbac_role_permission rp
  ON rp.role_id = ur.role_id
WHERE rp.grant_flag = 'Y'
  AND (ur.valid_to IS NULL OR ur.valid_to >= TRUNC(SYSDATE))

UNION ALL

SELECT DISTINCT
    gm.user_id,
    rp.action_id,
    'GROUP_ROLE' AS source_type
FROM rbac_group_membership gm
JOIN rbac_group_role gr
  ON gr.group_id = gm.group_id
JOIN rbac_role_permission rp
  ON rp.role_id = gr.role_id
WHERE rp.grant_flag = 'Y'
  AND (gm.valid_to IS NULL OR gm.valid_to >= TRUNC(SYSDATE))

UNION ALL

SELECT DISTINCT
    gm.user_id,
    gp.action_id,
    'GROUP_PERMISSION' AS source_type
FROM rbac_group_membership gm
JOIN rbac_group_permission gp
  ON gp.group_id = gm.group_id
WHERE gp.grant_flag = 'Y'
  AND (gm.valid_to IS NULL OR gm.valid_to >= TRUNC(SYSDATE));

