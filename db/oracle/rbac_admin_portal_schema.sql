CREATE OR REPLACE TRIGGER TRG_MstUser_ExpiryHist
AFTER UPDATE OF InactivatedOn, ActivatedOn, InactivatedBy, ActivatedBy ON TblMstRBACUser
FOR EACH ROW
DECLARE
    VHistUno NUMBER;
BEGIN
    IF :NEW.InactivatedOn IS NOT NULL
       AND (:OLD.InactivatedOn IS NULL OR :OLD.InactivatedOn <> :NEW.InactivatedOn) THEN
        INSERT INTO TblTrnRBACUserExpiryHist (
            UserUno, ExpiredOn, ExpirySourceCode, EventCommentEn,
            IsActive, EnteredOn, EnteredBy, ModifiedOn, ModifiedBy
        ) VALUES (
            :NEW.UserUno, :NEW.InactivatedOn, 'ACCOUNT_EXPIRED', :NEW.InactivationReasonEn,
            1, SYSTIMESTAMP, :NEW.InactivatedBy, SYSTIMESTAMP, :NEW.ModifiedBy
        );
    END IF;

    IF :NEW.ActivatedOn IS NOT NULL
       AND (:OLD.ActivatedOn IS NULL OR :OLD.ActivatedOn <> :NEW.ActivatedOn) THEN
        SELECT MAX(UserExpiryHistUno)
          INTO VHistUno
          FROM TblTrnRBACUserExpiryHist
         WHERE UserUno = :NEW.UserUno
           AND ReactivatedOn IS NULL
           AND DeletedOn IS NULL;

        IF VHistUno IS NOT NULL THEN
            UPDATE TblTrnRBACUserExpiryHist
               SET ReactivatedOn = :NEW.ActivatedOn,
                   ReactivatedBy = :NEW.ActivatedBy,
                   ModifiedOn = SYSTIMESTAMP,
                   ModifiedBy = NVL(:NEW.ModifiedBy, :NEW.ActivatedBy)
             WHERE UserExpiryHistUno = VHistUno;
        END IF;
    END IF;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        NULL;
END;
