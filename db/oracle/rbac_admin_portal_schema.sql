    group_id             NUMBER NOT NULL,
    user_id              NUMBER NOT NULL,
    membership_source_cd VARCHAR2(30) DEFAULT 'ORG_CHART' NOT NULL,
    valid_from           DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    valid_to             DATE,
    CONSTRAINT pk_rbac_group_membership PRIMARY KEY (group_id, user_id),
    CONSTRAINT fk_rbac_group_mem_group
        FOREIGN KEY (group_id) REFERENCES rbac_user_group(group_id),
    CONSTRAINT fk_rbac_group_mem_user
        FOREIGN KEY (user_id) REFERENCES rbac_user_account(user_id),
    CONSTRAINT ck_rbac_group_mem_source
