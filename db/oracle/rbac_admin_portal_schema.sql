--   * Master tables      : TblMstRBAC...
--   * Transaction tables : TblTrnRBAC...
--   * Primary key names  : ...Uno
--   * All primary keys are identity columns.
-- Bilingual support:
--   * English columns use suffix En (VARCHAR2)
--   * Arabic columns use suffix Ar (NVARCHAR2)
-- Audit fields:
--   * EnteredOn, EnteredBy, ModifiedOn, ModifiedBy, DeletedOn, DeletedBy
-- Active flag:
--   * IsActive NUMBER(1) in all tables (1=active, 0=inactive)

-- ============================================================
-- 1) MASTER TABLES (TblMstRBAC*)
-- ============================================================

