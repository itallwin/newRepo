);

CREATE INDEX ix_rbac_role_country_scope_country ON rbac_role_country_scope(country_id);

CREATE TABLE rbac_role_embassy_scope (
    role_id             NUMBER NOT NULL,
    embassy_id          NUMBER NOT NULL,
    CONSTRAINT pk_rbac_role_emb_scope PRIMARY KEY (role_id, embassy_id),
    CONSTRAINT fk_rbac_role_emb_scope_role
