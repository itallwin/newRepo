-- ============================================================
-- 3) HELPER VIEW
-- ============================================================
-- Effective user actions from:
--   a) Direct user-role permission
--   b) Group-role permission
--   c) Direct group permission
CREATE OR REPLACE VIEW VRBACEffectiveUserAction AS
SELECT DISTINCT
    U.UserUno,
    P.ActionUno,
    'USER_ROLE' AS SourceType
FROM TblMstRBACUser U
JOIN TblTrnRBACUserRole UR
  ON UR.UserUno = U.UserUno
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCd = 'ROLE'
 AND P.RoleUno = UR.RoleUno
WHERE P.GrantFlag = 'Y'
  AND (UR.ValidTo IS NULL OR UR.ValidTo >= TRUNC(SYSDATE))

UNION ALL

SELECT DISTINCT
    GM.UserUno,
    P.ActionUno,
    'GROUP_ROLE' AS SourceType
FROM TblTrnRBACGroupMembership GM
JOIN TblTrnRBACGroupRole GR
  ON GR.UserGroupUno = GM.UserGroupUno
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCd = 'ROLE'
 AND P.RoleUno = GR.RoleUno
WHERE P.GrantFlag = 'Y'
  AND (GM.ValidTo IS NULL OR GM.ValidTo >= TRUNC(SYSDATE))

UNION ALL

SELECT DISTINCT
    GM.UserUno,
    P.ActionUno,
    'GROUP_PERMISSION' AS SourceType
FROM TblTrnRBACGroupMembership GM
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCd = 'GROUP'
 AND P.UserGroupUno = GM.UserGroupUno
WHERE P.GrantFlag = 'Y'
  AND (GM.ValidTo IS NULL OR GM.ValidTo >= TRUNC(SYSDATE));

