    group_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id           NUMBER NOT NULL,
    group_code           VARCHAR2(50),
    group_name           VARCHAR2(150) NOT NULL,
    group_type_cd        VARCHAR2(30) NOT NULL,
    description_txt      VARCHAR2(1000),
    role_template_role_id NUMBER,
    estimated_members    NUMBER(8),
    membership_source_cd VARCHAR2(30) DEFAULT 'ORG_CHART' NOT NULL,
    status_cd            VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
