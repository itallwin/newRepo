);

CREATE INDEX ix_rbac_role_emb_scope_emb ON rbac_role_embassy_scope(embassy_id);

-- ============================================================
-- 4) USER MASTER + ROLE MAPPING
-- ============================================================

CREATE TABLE rbac_user_account (
    user_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id         VARCHAR2(40) NOT NULL,
    first_name          VARCHAR2(80) NOT NULL,
    last_name           VARCHAR2(80) NOT NULL,
    email_addr          VARCHAR2(255) NOT NULL,
    designation         VARCHAR2(120),
    company_id          NUMBER,
    department_id       NUMBER,
    external_subject_id VARCHAR2(200),
    status_cd           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    created_by          VARCHAR2(128),
    updated_at          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by          VARCHAR2(128),
    CONSTRAINT uq_rbac_user_employee UNIQUE (employee_id),
    CONSTRAINT uq_rbac_user_email UNIQUE (email_addr),
    CONSTRAINT fk_rbac_user_company
        FOREIGN KEY (company_id) REFERENCES rbac_company(company_id),
    CONSTRAINT fk_rbac_user_dept
        FOREIGN KEY (department_id) REFERENCES rbac_department(department_id),
    CONSTRAINT ck_rbac_user_status
        CHECK (status_cd IN ('ACTIVE', 'INACTIVE', 'LOCKED'))
);

CREATE INDEX ix_rbac_user_company ON rbac_user_account(company_id);
CREATE INDEX ix_rbac_user_dept ON rbac_user_account(department_id);

CREATE TABLE rbac_user_role (
    user_id             NUMBER NOT NULL,
    role_id             NUMBER NOT NULL,
    valid_from          DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    valid_to            DATE,
    assigned_reason     VARCHAR2(500),
    assigned_at         TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    assigned_by         VARCHAR2(128),
    CONSTRAINT pk_rbac_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_rbac_user_role_user
        FOREIGN KEY (user_id) REFERENCES rbac_user_account(user_id),
    CONSTRAINT fk_rbac_user_role_role
        FOREIGN KEY (role_id) REFERENCES rbac_role(role_id),
    CONSTRAINT ck_rbac_user_role_dates
        CHECK (valid_to IS NULL OR valid_to >= valid_from)
);

CREATE INDEX ix_rbac_user_role_role ON rbac_user_role(role_id);

