CREATE OR REPLACE TRIGGER TRG_MstUser_ValEmailDomain
BEFORE INSERT OR UPDATE OF EmailAddr ON TblMstRBACUser
FOR EACH ROW
DECLARE
    VDomain VARCHAR2(255);
    VCount  NUMBER;
    VAtPos  NUMBER;
BEGIN
    IF :NEW.EmailAddr IS NULL THEN
        RETURN;
    END IF;

    VAtPos := INSTR(:NEW.EmailAddr, '@', -1);
    IF VAtPos <= 1 OR VAtPos = LENGTH(:NEW.EmailAddr) THEN
        RAISE_APPLICATION_ERROR(-20051, 'Invalid EmailAddr format.');
    END IF;

    VDomain := LOWER(TRIM(SUBSTR(:NEW.EmailAddr, VAtPos + 1)));

    SELECT COUNT(1)
      INTO VCount
      FROM TblMstRBACAllowedEmailDomain D
     WHERE LOWER(D.EmailDomain) = VDomain
       AND D.IsActive = 1
       AND D.DeletedOn IS NULL;

    IF VCount = 0 THEN
        RAISE_APPLICATION_ERROR(-20052, 'Email domain not allowed in user master: ' || VDomain);
    END IF;
END;
/

-- Auto-derive expiry when not provided:
-- PERMANENT => EnteredOn + 12 months
-- EXTERNAL  => EnteredOn + 6 months
CREATE OR REPLACE TRIGGER TRG_MstUser_SetExpiry
BEFORE INSERT OR UPDATE OF StaffTypeCode, EnteredOn, AccountExpiryOn ON TblMstRBACUser
FOR EACH ROW
DECLARE
    VBaseTs TIMESTAMP(6);
BEGIN
    VBaseTs := NVL(:NEW.EnteredOn, SYSTIMESTAMP);

    IF :NEW.StaffTypeCode IS NULL THEN
        :NEW.StaffTypeCode := 'PERMANENT';
    END IF;

    IF :NEW.AccountExpiryOn IS NULL THEN
        IF :NEW.StaffTypeCode = 'EXTERNAL' THEN
            :NEW.AccountExpiryOn := CAST(ADD_MONTHS(CAST(VBaseTs AS DATE), 6) AS TIMESTAMP);
        ELSE
            :NEW.AccountExpiryOn := CAST(ADD_MONTHS(CAST(VBaseTs AS DATE), 12) AS TIMESTAMP);
        END IF;
    END IF;
END;
/

