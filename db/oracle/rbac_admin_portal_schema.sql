-- Permission grants:
-- GranteeTypeCd='ROLE'  => RoleUno is used
-- GranteeTypeCd='GROUP' => UserGroupUno is used
CREATE TABLE TblTrnRBACPermission (
    PermissionUno       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    GranteeTypeCd       VARCHAR2(20) NOT NULL,
    RoleUno             NUMBER,
    UserGroupUno        NUMBER,
    ActionUno           NUMBER NOT NULL,
    GrantFlag           CHAR(1) DEFAULT 'Y' NOT NULL,
    GrantedAt           TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    GrantedBy           VARCHAR2(128),
    CONSTRAINT FK_TrnRBACPerm_Role FOREIGN KEY (RoleUno) REFERENCES TblMstRBACRole(RoleUno),
    CONSTRAINT FK_TrnRBACPerm_Group FOREIGN KEY (UserGroupUno) REFERENCES TblMstRBACUserGroup(UserGroupUno),
    CONSTRAINT FK_TrnRBACPerm_Action FOREIGN KEY (ActionUno) REFERENCES TblMstRBACAction(ActionUno),
    CONSTRAINT CK_TrnRBACPerm_GranteeType CHECK (GranteeTypeCd IN ('ROLE', 'GROUP')),
    CONSTRAINT CK_TrnRBACPerm_GrantFlag CHECK (GrantFlag IN ('Y', 'N')),
    CONSTRAINT CK_TrnRBACPerm_GranteeRef CHECK (
        (GranteeTypeCd = 'ROLE' AND RoleUno IS NOT NULL AND UserGroupUno IS NULL) OR
        (GranteeTypeCd = 'GROUP' AND UserGroupUno IS NOT NULL AND RoleUno IS NULL)
    ),
    CONSTRAINT UQ_TrnRBACPermission UNIQUE (GranteeTypeCd, RoleUno, UserGroupUno, ActionUno)
);

CREATE INDEX IX_TrnRBACPermission_Action ON TblTrnRBACPermission(ActionUno);
CREATE INDEX IX_TrnRBACPermission_Role ON TblTrnRBACPermission(RoleUno);
CREATE INDEX IX_TrnRBACPermission_Group ON TblTrnRBACPermission(UserGroupUno);

