CREATE OR REPLACE VIEW VRBACUserUsageDailyStat AS
SELECT
    TRUNC(A.ActivityOn) AS UsageOn,
    A.UserUno,
    A.PageUno,
    A.ActionUno,
    COUNT(1) AS TotalEventCount,
    SUM(CASE WHEN A.ActivityTypeCode = 'PAGE_VIEW' THEN 1 ELSE 0 END) AS PageViewCount,
    SUM(CASE WHEN A.ActivityTypeCode = 'ACTION_EXECUTE' THEN 1 ELSE 0 END) AS ActionExecCount,
    SUM(CASE WHEN NVL(A.IsAuthorized, 1) = 0 THEN 1 ELSE 0 END) AS UnauthorizedCount
FROM TblTrnRBACUserActivity A
WHERE A.IsActive = 1
  AND A.DeletedOn IS NULL
GROUP BY TRUNC(A.ActivityOn), A.UserUno, A.PageUno, A.ActionUno;

CREATE OR REPLACE VIEW VRBACAppUsageDailyStat AS
SELECT
    TRUNC(A.ActivityOn) AS UsageOn,
    A.ModuleUno,
    A.PageUno,
    A.ActionUno,
    COUNT(1) AS TotalEventCount,
    COUNT(DISTINCT A.UserUno) AS DistinctUserCount,
    SUM(CASE WHEN A.ActivityTypeCode = 'PAGE_VIEW' THEN 1 ELSE 0 END) AS PageViewCount,
    SUM(CASE WHEN A.ActivityTypeCode = 'ACTION_EXECUTE' THEN 1 ELSE 0 END) AS ActionExecCount
FROM TblTrnRBACUserActivity A
WHERE A.IsActive = 1
  AND A.DeletedOn IS NULL
GROUP BY TRUNC(A.ActivityOn), A.ModuleUno, A.PageUno, A.ActionUno;

-- Effective user actions from:
--   a) Direct user-role permission
--   b) Group-role permission
--   c) Direct group permission
CREATE OR REPLACE VIEW VRBACEffectiveUserAction AS
SELECT DISTINCT
    U.UserUno,
    P.ActionUno,
    'USER_ROLE' AS SourceType
FROM TblMstRBACUser U
JOIN TblTrnRBACUserRole UR
  ON UR.UserUno = U.UserUno
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCode = 'ROLE'
 AND P.RoleUno = UR.RoleUno
WHERE U.IsActive = 1
  AND U.DeletedOn IS NULL
  AND UR.IsActive = 1
  AND UR.DeletedOn IS NULL
  AND P.IsActive = 1
  AND P.DeletedOn IS NULL
  AND P.GrantAcess = 'Y'
  AND (UR.ValidTo IS NULL OR UR.ValidTo >= TRUNC(SYSDATE))

UNION ALL

SELECT DISTINCT
    GM.UserUno,
    P.ActionUno,
    'GROUP_ROLE' AS SourceType
FROM TblTrnRBACGroupMembership GM
JOIN TblTrnRBACGroupRole GR
  ON GR.UserGroupUno = GM.UserGroupUno
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCode = 'ROLE'
 AND P.RoleUno = GR.RoleUno
WHERE GM.IsActive = 1
  AND GM.DeletedOn IS NULL
  AND GR.IsActive = 1
  AND GR.DeletedOn IS NULL
  AND P.IsActive = 1
  AND P.DeletedOn IS NULL
  AND P.GrantAcess = 'Y'
  AND (GM.ValidTo IS NULL OR GM.ValidTo >= TRUNC(SYSDATE))

UNION ALL

SELECT DISTINCT
    GM.UserUno,
    P.ActionUno,
    'GROUP_PERMISSION' AS SourceType
FROM TblTrnRBACGroupMembership GM
JOIN TblTrnRBACPermission P
  ON P.GranteeTypeCode = 'GROUP'
 AND P.UserGroupUno = GM.UserGroupUno
WHERE GM.IsActive = 1
  AND GM.DeletedOn IS NULL
  AND P.IsActive = 1
  AND P.DeletedOn IS NULL
  AND P.GrantAcess = 'Y'
  AND (GM.ValidTo IS NULL OR GM.ValidTo >= TRUNC(SYSDATE));

