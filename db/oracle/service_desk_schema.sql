-- ITIL Service Desk schema for Oracle Database
-- Naming convention aligned with Admin Portal table design:
--   * Master tables      : TblMstSD...
--   * Transaction tables : TblTrnSD...
--   * Primary key names  : ...Uno
--   * Identity PK on all tables
--   * IsActive NUMBER(1) in all tables
--   * Audit fields: EnteredOn/By, ModifiedOn/By, DeletedOn/By

-- ============================================================
-- 1) MASTER TABLES (TblMstSD*)
-- ============================================================

CREATE TABLE TblMstSDSupportLevel (
