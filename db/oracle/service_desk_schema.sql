LEFT JOIN TblMstSDTicketStatus ts ON ts.TicketStatusUno = t.TicketStatusUno
LEFT JOIN TblMstSDPriority p ON p.PriorityUno = t.PriorityUno
LEFT JOIN TblTrnSDEscalation e ON e.TicketUno = t.TicketUno AND e.IsActive = 1
LEFT JOIN TblTrnSDFeedback fb ON fb.TicketUno = t.TicketUno AND fb.IsActive = 1
WHERE t.IsActive = 1;

