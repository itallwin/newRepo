CREATE OR REPLACE VIEW VRptSDAgentKPILive AS
SELECT
    u.UserUno AS AgentUserUno,
    u.DisplayNameEn AS AgentNameEn,
    u.TeamUno,
    u.DepartmentUno,
    u.SectionUno,
    SUM(CASE WHEN t.TicketUno IS NOT NULL AND NVL(ts.IsTerminal,0)=0 THEN 1 ELSE 0 END) AS OpenTicketCount,
    SUM(
        CASE
            WHEN t.TicketUno IS NOT NULL
                 AND NVL(ts.IsTerminal,0)=0
                 AND SYSTIMESTAMP > NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
            THEN 1 ELSE 0
        END
    ) AS DelayedTicketCount,
    ROUND(
        100 * SUM(
            CASE
                WHEN t.TicketUno IS NOT NULL
                     AND NVL(ts.IsTerminal,0)=0
                     AND SYSTIMESTAMP > NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                THEN 1 ELSE 0
            END
        ) / NULLIF(SUM(CASE WHEN t.TicketUno IS NOT NULL AND NVL(ts.IsTerminal,0)=0 THEN 1 ELSE 0 END),0),
        2
    ) AS DelayedPercent,
    ROUND(
        AVG(
            CASE
                WHEN t.ResolvedOn IS NOT NULL
                     AND t.ResolvedOn >= SYSTIMESTAMP - NUMTODSINTERVAL(7,'DAY')
                THEN (CAST(t.ResolvedOn AS DATE) - CAST(t.CreatedOn AS DATE)) * 24
            END
        ),
        2
    ) AS AvgResolutionHours7D,
    ROUND(
        100 * SUM(
            CASE
                WHEN t.CreatedOn >= SYSTIMESTAMP - NUMTODSINTERVAL(30,'DAY')
                     AND t.FirstResponseOn IS NOT NULL
                     AND t.FirstResponseOn <= NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                THEN 1 ELSE 0
            END
        ) / NULLIF(SUM(CASE WHEN t.CreatedOn >= SYSTIMESTAMP - NUMTODSINTERVAL(30,'DAY') THEN 1 ELSE 0 END),0),
        2
    ) AS SLACompliancePct30D,
    SUM(CASE WHEN e.EscalationUno IS NOT NULL AND e.EscalatedOn >= SYSTIMESTAMP - NUMTODSINTERVAL(30,'DAY') THEN 1 ELSE 0 END) AS EscalationInCount30D
FROM TblMstSDUser u
LEFT JOIN TblTrnSDTicket t
       ON t.AssignedToUserUno = u.UserUno
      AND t.IsActive = 1
LEFT JOIN TblMstSDTicketStatus ts
       ON ts.TicketStatusUno = t.TicketStatusUno
LEFT JOIN TblMstSDPriority p
       ON p.PriorityUno = t.PriorityUno
LEFT JOIN TblTrnSDEscalation e
       ON e.TicketUno = t.TicketUno
      AND e.ToSupportLevelUno = u.SupportLevelUno
      AND e.IsActive = 1
WHERE u.IsAgent = 1
  AND u.IsActive = 1
GROUP BY u.UserUno, u.DisplayNameEn, u.TeamUno, u.DepartmentUno, u.SectionUno;

CREATE OR REPLACE VIEW VRptSDOverallKPILive AS
SELECT
    COUNT(*) AS TotalTicketCount,
    SUM(CASE WHEN NVL(ts.IsTerminal,0)=0 THEN 1 ELSE 0 END) AS OpenTicketCount,
    SUM(
        CASE
            WHEN NVL(ts.IsTerminal,0)=0
                 AND SYSTIMESTAMP > NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
            THEN 1 ELSE 0
        END
    ) AS DelayedTicketCount,
    ROUND(
        100 * SUM(
            CASE
                WHEN t.CreatedOn >= SYSTIMESTAMP - NUMTODSINTERVAL(30,'DAY')
                     AND t.FirstResponseOn IS NOT NULL
                     AND t.FirstResponseOn <= NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                THEN 1 ELSE 0
            END
        ) / NULLIF(SUM(CASE WHEN t.CreatedOn >= SYSTIMESTAMP - NUMTODSINTERVAL(30,'DAY') THEN 1 ELSE 0 END),0),
        2
    ) AS OverallSLACompliancePct30D,
    ROUND(
        AVG(CASE WHEN t.ResolvedOn IS NOT NULL THEN (CAST(t.ResolvedOn AS DATE) - CAST(t.CreatedOn AS DATE)) * 24 END),
        2
    ) AS AvgResolutionHours,
    SUM(CASE WHEN e.EscalationUno IS NOT NULL AND e.EscalatedOn >= SYSTIMESTAMP - NUMTODSINTERVAL(30,'DAY') THEN 1 ELSE 0 END) AS EscalationCount30D,
