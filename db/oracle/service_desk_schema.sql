    t.SubTypeUno,
    st.SubTypeNameEn,
    COUNT(*) AS RepeatedTicketCount30D,
    SUM(CASE WHEN p.PriorityCode IN ('P1','P2') THEN 1 ELSE 0 END) AS HighPriorityCount30D,
    ROUND(LEAST(99, (COUNT(*) * 12) + (SUM(CASE WHEN p.PriorityCode IN ('P1','P2') THEN 1 ELSE 0 END) * 6)), 2) AS ConfidencePercent,
    'Recurring issues in ' || NVL(svc.ServiceNameEn, 'Unspecified Service') || ' / ' || NVL(st.SubTypeNameEn, 'General') AS SuggestedProblemTitleEn
FROM TblTrnSDTicket t
JOIN TblMstSDTicketType tt ON tt.TicketTypeUno = t.TicketTypeUno
LEFT JOIN TblMstSDAffectedService svc ON svc.AffectedServiceUno = t.AffectedServiceUno
LEFT JOIN TblMstSDCategory c ON c.CategoryUno = t.CategoryUno
LEFT JOIN TblMstSDSubType st ON st.SubTypeUno = t.SubTypeUno
LEFT JOIN TblMstSDPriority p ON p.PriorityUno = t.PriorityUno
WHERE t.IsActive = 1
  AND tt.TicketTypeCode IN ('INCIDENT','SERVICE_REQUEST')
  AND t.CreatedOn >= SYSTIMESTAMP - NUMTODSINTERVAL(30,'DAY')
GROUP BY t.AffectedServiceUno, svc.ServiceNameEn, t.CategoryUno, c.CategoryNameEn, t.SubTypeUno, st.SubTypeNameEn
HAVING COUNT(*) >= 3;

-- Tickets that crossed configured auto-escalation thresholds
CREATE OR REPLACE VIEW VRptSDAutoEscalationDue AS
SELECT
    t.TicketUno,
    t.TicketNo,
    t.CurrentSupportLevelUno,
    r.AutoEscalationRuleUno,
    r.RuleCode,
    r.ToSupportLevelUno,
    ROUND((CAST(SYSTIMESTAMP AS DATE) - CAST(t.CreatedOn AS DATE)) * 24 * 60, 2) AS ElapsedMinutes,
    ROUND(NVL(p.ResponseSlaHours,24) * 60, 2) AS SlaMinutes,
    ROUND(((CAST(SYSTIMESTAMP AS DATE) - CAST(t.CreatedOn AS DATE)) * 24 * 60) / NULLIF((NVL(p.ResponseSlaHours,24) * 60),0) * 100, 2) AS ConsumedSlaPercent
FROM TblTrnSDTicket t
JOIN TblMstSDTicketStatus ts ON ts.TicketStatusUno = t.TicketStatusUno
JOIN TblMstSDPriority p ON p.PriorityUno = t.PriorityUno
JOIN TblMstSDAutoEscalationRule r
  ON r.IsActive = 1
 AND (r.TicketTypeUno IS NULL OR r.TicketTypeUno = t.TicketTypeUno)
 AND (r.PriorityUno IS NULL OR r.PriorityUno = t.PriorityUno)
 AND (r.FromSupportLevelUno IS NULL OR r.FromSupportLevelUno = t.CurrentSupportLevelUno)
WHERE t.IsActive = 1
  AND NVL(ts.IsTerminal,0) = 0
  AND (
      (r.TriggerAfterMinutes IS NOT NULL AND ((CAST(SYSTIMESTAMP AS DATE) - CAST(t.CreatedOn AS DATE)) * 24 * 60) >= r.TriggerAfterMinutes)
      OR
      (r.TriggerPercentSla IS NOT NULL AND (((CAST(SYSTIMESTAMP AS DATE) - CAST(t.CreatedOn AS DATE)) * 24 * 60) / NULLIF((NVL(p.ResponseSlaHours,24) * 60),0) * 100) >= r.TriggerPercentSla)
  )
  AND NOT EXISTS (
      SELECT 1
      FROM TblTrnSDAutoEscalationAudit a
      WHERE a.TicketUno = t.TicketUno
        AND a.AutoEscalationRuleUno = r.AutoEscalationRuleUno
        AND a.ActionCode = 'ESCALATED'
        AND a.IsActive = 1
  );

-- Weekly/Monthly/Quarterly management summary for service request impact
CREATE OR REPLACE VIEW VRptSDServiceRequestSummaryPeriod AS
SELECT
    'WEEKLY' AS PeriodTypeCode,
    TRUNC(CAST(t.CreatedOn AS DATE), 'IW') AS PeriodStartDate,
    TRUNC(CAST(t.CreatedOn AS DATE), 'IW') + 6 AS PeriodEndDate,
    COUNT(*) AS ServiceRequestCount,
    SUM(CASE WHEN i.ImpactCode = 'HIGH' THEN 1 ELSE 0 END) AS HighImpactCount,
    SUM(
        CASE
            WHEN SYSTIMESTAMP > NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                 AND NVL(ts.IsTerminal,0)=0
            THEN 1 ELSE 0
        END
    ) AS DelayedCount,
    ROUND(
        100 * SUM(
            CASE
                WHEN t.FirstResponseOn IS NOT NULL
                     AND t.FirstResponseOn <= NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                THEN 1 ELSE 0
            END
        ) / NULLIF(COUNT(*),0),
        2
    ) AS SLACompliancePct
FROM TblTrnSDTicket t
JOIN TblMstSDTicketType tt ON tt.TicketTypeUno = t.TicketTypeUno AND tt.TicketTypeCode = 'SERVICE_REQUEST'
LEFT JOIN TblMstSDImpact i ON i.ImpactUno = t.ImpactUno
LEFT JOIN TblMstSDPriority p ON p.PriorityUno = t.PriorityUno
LEFT JOIN TblMstSDTicketStatus ts ON ts.TicketStatusUno = t.TicketStatusUno
WHERE t.IsActive = 1
GROUP BY TRUNC(CAST(t.CreatedOn AS DATE), 'IW')
UNION ALL
SELECT
    'MONTHLY' AS PeriodTypeCode,
    TRUNC(CAST(t.CreatedOn AS DATE), 'MM') AS PeriodStartDate,
    LAST_DAY(CAST(t.CreatedOn AS DATE)) AS PeriodEndDate,
    COUNT(*) AS ServiceRequestCount,
    SUM(CASE WHEN i.ImpactCode = 'HIGH' THEN 1 ELSE 0 END) AS HighImpactCount,
    SUM(
        CASE
            WHEN SYSTIMESTAMP > NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                 AND NVL(ts.IsTerminal,0)=0
            THEN 1 ELSE 0
        END
    ) AS DelayedCount,
    ROUND(
        100 * SUM(
            CASE
                WHEN t.FirstResponseOn IS NOT NULL
                     AND t.FirstResponseOn <= NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                THEN 1 ELSE 0
            END
        ) / NULLIF(COUNT(*),0),
        2
    ) AS SLACompliancePct
FROM TblTrnSDTicket t
JOIN TblMstSDTicketType tt ON tt.TicketTypeUno = t.TicketTypeUno AND tt.TicketTypeCode = 'SERVICE_REQUEST'
LEFT JOIN TblMstSDImpact i ON i.ImpactUno = t.ImpactUno
LEFT JOIN TblMstSDPriority p ON p.PriorityUno = t.PriorityUno
LEFT JOIN TblMstSDTicketStatus ts ON ts.TicketStatusUno = t.TicketStatusUno
WHERE t.IsActive = 1
GROUP BY TRUNC(CAST(t.CreatedOn AS DATE), 'MM'), LAST_DAY(CAST(t.CreatedOn AS DATE))
UNION ALL
SELECT
    'QUARTERLY' AS PeriodTypeCode,
    TRUNC(CAST(t.CreatedOn AS DATE), 'Q') AS PeriodStartDate,
    ADD_MONTHS(TRUNC(CAST(t.CreatedOn AS DATE), 'Q'), 3) - 1 AS PeriodEndDate,
    COUNT(*) AS ServiceRequestCount,
    SUM(CASE WHEN i.ImpactCode = 'HIGH' THEN 1 ELSE 0 END) AS HighImpactCount,
    SUM(
        CASE
            WHEN SYSTIMESTAMP > NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                 AND NVL(ts.IsTerminal,0)=0
            THEN 1 ELSE 0
        END
    ) AS DelayedCount,
    ROUND(
        100 * SUM(
            CASE
                WHEN t.FirstResponseOn IS NOT NULL
                     AND t.FirstResponseOn <= NVL(t.ResponseSlaDueOn, t.CreatedOn + NUMTODSINTERVAL(NVL(p.ResponseSlaHours,24),'HOUR'))
                THEN 1 ELSE 0
            END
        ) / NULLIF(COUNT(*),0),
        2
    ) AS SLACompliancePct
FROM TblTrnSDTicket t
JOIN TblMstSDTicketType tt ON tt.TicketTypeUno = t.TicketTypeUno AND tt.TicketTypeCode = 'SERVICE_REQUEST'
LEFT JOIN TblMstSDImpact i ON i.ImpactUno = t.ImpactUno
LEFT JOIN TblMstSDPriority p ON p.PriorityUno = t.PriorityUno
LEFT JOIN TblMstSDTicketStatus ts ON ts.TicketStatusUno = t.TicketStatusUno
WHERE t.IsActive = 1
GROUP BY TRUNC(CAST(t.CreatedOn AS DATE), 'Q'), ADD_MONTHS(TRUNC(CAST(t.CreatedOn AS DATE), 'Q'), 3) - 1;

